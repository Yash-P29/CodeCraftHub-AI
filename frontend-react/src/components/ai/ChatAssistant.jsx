import React, { useState, useRef, useEffect } from 'react';
import { aiApi } from '../../services/aiApi';
import { formatMarkdown } from '../../utils/markdown';

export default function ChatAssistant({ sessionId, onShowToast }) {
  const [messages, setMessages] = useState([]);
  const [inputVal, setInputVal] = useState('');
  const [isGenerating, setIsGenerating] = useState(false);
  const messagesEndRef = useRef(null);

  const suggestedPrompts = [
    { label: 'Explain React hooks', prompt: 'Explain React hooks in simple terms with a code example.' },
    { label: 'REST vs. GraphQL', prompt: 'What is the difference between REST APIs and GraphQL?' },
    { label: 'How Docker works', prompt: 'How does Docker containerization work under the hood?' },
    { label: 'MVC Architecture', prompt: 'Explain the MVC architectural pattern in full-stack development.' },
    { label: 'Backend Prerequisites', prompt: 'What should I learn before starting backend development with Node.js?' }
  ];

  const scrollToBottom = () => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  };

  useEffect(() => {
    scrollToBottom();
  }, [messages, isGenerating]);

  const handleSubmit = async (e) => {
    if (e) e.preventDefault();
    const text = inputVal.trim();
    if (!text || isGenerating) return;

    setInputVal('');
    const newMessages = [...messages, { role: 'user', content: text }];
    setMessages(newMessages);
    setIsGenerating(true);

    try {
      // Build history for multi-turn Gemini context
      const history = messages
        .filter((m) => m.role === 'user' || m.role === 'model')
        .map((m) => ({ role: m.role, content: m.content }));

      const data = await aiApi.sendChatMessage(text, history, sessionId);
      setMessages((prev) => [
        ...prev,
        {
          role: 'model',
          content: data.response,
          model: data.model,
          latency: data.latency
        }
      ]);
    } catch (err) {
      setMessages((prev) => [
        ...prev,
        {
          role: 'error',
          content: `Error: ${err.message}`
        }
      ]);
      onShowToast('Chat Error', err.message, 'danger');
    } finally {
      setIsGenerating(false);
    }
  };

  const handleChipClick = (prompt) => {
    setInputVal(prompt);
  };

  const handleClearSession = () => {
    if (window.confirm('Clear current learning assistant session history?')) {
      setMessages([]);
    }
  };

  return (
    <div id="ai-assistant-section" className="ai-section-wrapper">
      <div className="chat-card">
        <div className="chat-header">
          <div className="chat-header-title">
            <div
              className="instructor-avatar"
              style={{ background: 'linear-gradient(135deg, var(--primary), #4F46E5)' }}
            >
              <i className="fa-solid fa-brain"></i>
            </div>
            <div>
              <h3>CodeCraft AI Learning Assistant</h3>
              <p style={{ fontSize: '0.75rem', color: 'var(--text-secondary)' }}>
                Direct Generative AI inference powered by Google Gemini
              </p>
            </div>
          </div>
          <button
            id="clear-chat-btn"
            className="btn-subtle"
            onClick={handleClearSession}
            title="Clear current session messages"
          >
            <i className="fa-solid fa-trash-can"></i> Clear Session
          </button>
        </div>

        <div id="chat-messages" className="chat-messages">
          {messages.length === 0 ? (
            <div className="chat-empty-intro">
              <div className="intro-avatar">
                <i className="fa-solid fa-brain"></i>
              </div>
              <h4>CodeCraft AI Learning Assistant</h4>
              <p>
                Ask technical questions, architectural explanations, code reviews, or conceptual comparisons.
              </p>
            </div>
          ) : (
            messages.map((m, idx) => (
              <div key={idx} className={`chat-bubble chat-${m.role}`}>
                <div className={`bubble-avatar ${m.role === 'user' ? 'user-av' : 'ai-av'}`}>
                  <i className={`fa-solid ${m.role === 'user' ? 'fa-user' : 'fa-sparkles'}`}></i>
                </div>
                <div className="bubble-content">
                  <div
                    className="bubble-text"
                    dangerouslySetInnerHTML={{
                      __html: m.role === 'model' ? formatMarkdown(m.content) : m.content
                    }}
                  />
                  {m.role === 'model' && m.model && (
                    <div className="chat-meta">
                      Generated by {m.model} &bull; {m.latency ? m.latency + 's' : 'live'}
                    </div>
                  )}
                </div>
              </div>
            ))
          )}

          {isGenerating && (
            <div className="chat-bubble chat-model typing-indicator">
              <div className="bubble-avatar ai-av">
                <i className="fa-solid fa-sparkles"></i>
              </div>
              <div className="bubble-content">
                <div className="typing-dots">
                  <span></span>
                  <span></span>
                  <span></span>
                </div>
              </div>
            </div>
          )}
          <div ref={messagesEndRef} />
        </div>

        <div className="prompt-chips-bar">
          <span className="prompt-chips-label">
            <i className="fa-regular fa-lightbulb"></i> Suggested:
          </span>
          {suggestedPrompts.map((p, i) => (
            <button
              key={i}
              type="button"
              className="prompt-chip"
              onClick={() => handleChipClick(p.prompt)}
            >
              {p.label}
            </button>
          ))}
        </div>

        <div className="chat-input-bar">
          <form id="ai-chat-form" className="chat-input-form" onSubmit={handleSubmit}>
            <input
              type="text"
              id="ai-chat-input"
              className="chat-input-field"
              placeholder="Ask a technical or programming question..."
              value={inputVal}
              onChange={(e) => setInputVal(e.target.value)}
              autoComplete="off"
            />
            <button type="submit" className="btn-primary" disabled={isGenerating}>
              <i className="fa-solid fa-paper-plane"></i>
              <span>Send</span>
            </button>
          </form>
        </div>
      </div>
    </div>
  );
}
